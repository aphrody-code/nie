/**
 * Applique la transformation déclarée par une variante à un texte du jeu.
 *
 * Séparée de la table pour que la substitution passe par une fonction unique : un composant qui
 * écrirait `entry.fr.toUpperCase()` lui-même retrouverait « ÉMÉRITE » là où le libellé est
 * « Émérite », et la différence ne se verrait qu'à l'écran.
 */
export function applyTransform(transform: UiTextVariant["transform"], text: string): string {
	switch (transform) {
		case "upper":
			return text.toLocaleUpperCase("fr");
		case "lower":
			return text.toLocaleLowerCase("fr");
		case "capitalize":
			return text.slice(0, 1).toLocaleUpperCase("fr") + text.slice(1).toLocaleLowerCase("fr");
		case "apostrophe":
			// Le jeu écrit l'apostrophe droite ; l'interface, la typographique.
			return text.replaceAll("'", "’");
	}
}

/** Retrouve une entrée par son libellé écrit à la main. */
export function findUiText(label: string): UiTextEntry | undefined {
	return UI_TEXT_MAP.find(entry => entry.label === label)
		?? UI_TEXT_VARIANTS.find(entry => entry.label === label);
}
